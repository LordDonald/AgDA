-- AgDA staging analytics bootstrap (PostgreSQL 10+).
--
-- Execute ONLY against a verified, dedicated staging analytics database. Product
-- events do not store an environment column; sharing the production database
-- would mix staging activity with production activity. Verify the service and
-- database destination independently; never copy production rows or secrets.
--
-- Before executing, inspect any existing tables/views, their ownership, columns,
-- constraints and privileges. This is a bootstrap for an empty database or an
-- exact rerun of this schema, NOT a migration for an unknown existing schema.
-- CREATE TABLE IF NOT EXISTS intentionally does not repair incompatible tables.
-- CREATE OR REPLACE VIEW can reject incompatible existing column types/order;
-- do not drop an existing object to bypass such a failure.
--
-- Requirements: public schema exists; the bootstrap role owns these objects or
-- has the necessary create/replace permissions; the application role can insert
-- product_events, insert/update/select product_feedback, use their identity
-- sequences, and select the five views. Application connections must resolve
-- unqualified object names to this public schema. No roles/grants are changed.
--
-- After independently verifying the target, set this session marker:
--   SELECT set_config('agda.bootstrap_environment', 'staging', false);
-- Then execute this file with stop-on-error enabled (psql: -v ON_ERROR_STOP=1),
-- or as one driver execute call that propagates errors. Keep credentials out of
-- command output and logs. The transaction prevents a partially applied schema.
--
-- Validation: apply twice; verify all five result shapes using the current
-- packages/contracts/internal_analytics.py models, including empty tables.
-- Exercise the current application's product event insert/deduplication and
-- feedback insert/update with synthetic staging requests, then verify their SQL
-- rows after an API restart. Unit tests mock SQL and cannot prove persistence.
-- No schema initialization occurs automatically in the API runtime.

BEGIN;

DO $bootstrap_guard$
BEGIN
    IF current_setting('agda.bootstrap_environment', true)
        IS DISTINCT FROM 'staging' THEN
        RAISE EXCEPTION 'Dedicated staging database verification is required before bootstrap';
    END IF;
END;
$bootstrap_guard$;

CREATE TABLE IF NOT EXISTS public.product_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_name text NOT NULL,
    event_timestamp timestamptz NOT NULL,
    request_id varchar(128) NOT NULL,
    status text NOT NULL,
    metric_id text,
    operation text,
    group_by text,
    was_follow_up boolean NOT NULL DEFAULT false,
    question_length integer NOT NULL CHECK (question_length >= 0),
    result_count integer NOT NULL DEFAULT 0 CHECK (result_count >= 0),
    evidence_grade text,
    visualization_recommended boolean NOT NULL DEFAULT false,
    processing_duration_ms double precision NOT NULL
        CHECK (processing_duration_ms >= 0),
    data_version text NOT NULL,
    metric_version text,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT product_events_request_event_unique
        UNIQUE (request_id, event_name)
);

CREATE TABLE IF NOT EXISTS public.product_feedback (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id varchar(128) NOT NULL UNIQUE,
    rating text NOT NULL CHECK (rating IN ('helpful', 'not_helpful')),
    reason_code text CHECK (
        reason_code IN (
            'incorrect', 'unclear', 'not_relevant',
            'insufficient_evidence', 'other'
        )
    ),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (rating <> 'helpful' OR reason_code IS NULL)
);

-- The application checks that an agda_question event exists when upserting
-- feedback. request_id alone is not unique in product_events (the unique key
-- includes event_name), so no incompatible single-column foreign key is added.
-- All question views exclude other event types. The unique keys above prevent
-- feedback joins from multiplying question counts.

CREATE OR REPLACE VIEW public.analytics_overview AS
WITH questions AS (
    SELECT
        count(*) AS total_questions,
        count(*) FILTER (WHERE status = 'answered') AS answered_count,
        count(*) FILTER (WHERE status = 'needs_clarification') AS clarification_count,
        count(*) FILTER (WHERE status = 'reframe_required') AS reframe_count,
        count(*) FILTER (WHERE status = 'unsupported') AS unsupported_count,
        count(*) FILTER (WHERE was_follow_up) AS follow_up_count,
        100.0 * count(*) FILTER (WHERE was_follow_up)
            / nullif(count(*), 0) AS follow_up_rate_pct,
        count(*) FILTER (WHERE visualization_recommended) AS visualization_count,
        avg(processing_duration_ms) AS avg_processing_ms,
        percentile_cont(0.95) WITHIN GROUP (ORDER BY processing_duration_ms)
            AS p95_processing_ms
    FROM public.product_events
    WHERE event_name = 'agda_question'
), feedback AS (
    SELECT
        count(*) AS feedback_count,
        count(*) FILTER (WHERE feedback.rating = 'helpful') AS helpful_count,
        count(*) FILTER (WHERE feedback.rating = 'not_helpful') AS not_helpful_count,
        100.0 * count(*) FILTER (WHERE feedback.rating = 'helpful')
            / nullif(count(*), 0) AS helpful_rate_pct
    FROM public.product_feedback AS feedback
    JOIN public.product_events AS event
        ON event.request_id = feedback.request_id
        AND event.event_name = 'agda_question'
)
SELECT
    questions.total_questions,
    questions.answered_count,
    questions.clarification_count,
    questions.reframe_count,
    questions.unsupported_count,
    questions.follow_up_count,
    questions.follow_up_rate_pct,
    questions.visualization_count,
    questions.avg_processing_ms,
    questions.p95_processing_ms,
    feedback.feedback_count,
    feedback.helpful_count,
    feedback.not_helpful_count,
    feedback.helpful_rate_pct
FROM questions CROSS JOIN feedback;

-- Calendar dates are always UTC, independent of the connection time zone.
CREATE OR REPLACE VIEW public.analytics_daily_usage AS
SELECT
    (event_timestamp AT TIME ZONE 'UTC')::date AS usage_date,
    count(*) AS total_questions,
    count(*) FILTER (WHERE status = 'answered') AS answered_count,
    count(*) FILTER (WHERE status = 'needs_clarification') AS clarification_count,
    count(*) FILTER (WHERE status = 'reframe_required') AS reframe_count,
    count(*) FILTER (WHERE status = 'unsupported') AS unsupported_count,
    count(*) FILTER (WHERE was_follow_up) AS follow_up_count,
    100.0 * count(*) FILTER (WHERE was_follow_up)
        / nullif(count(*), 0) AS follow_up_rate_pct,
    count(*) FILTER (WHERE visualization_recommended) AS visualization_count,
    avg(processing_duration_ms) AS avg_processing_ms,
    percentile_cont(0.95) WITHIN GROUP (ORDER BY processing_duration_ms)
        AS p95_processing_ms
FROM public.product_events
WHERE event_name = 'agda_question'
GROUP BY (event_timestamp AT TIME ZONE 'UTC')::date;

-- Questions without a resolved metric remain in overview/status/daily totals;
-- the metric view returns only named metrics as required by its API contract.
CREATE OR REPLACE VIEW public.analytics_metric_usage AS
SELECT
    event.metric_id,
    count(*) AS question_count,
    count(*) FILTER (WHERE event.was_follow_up) AS follow_up_count,
    avg(event.processing_duration_ms) AS avg_processing_ms,
    percentile_cont(0.95) WITHIN GROUP (ORDER BY event.processing_duration_ms)
        AS p95_processing_ms,
    count(feedback.id) AS feedback_count,
    count(feedback.id) FILTER (WHERE feedback.rating = 'helpful') AS helpful_count,
    count(feedback.id) FILTER (WHERE feedback.rating = 'not_helpful') AS not_helpful_count,
    100.0 * count(feedback.id) FILTER (WHERE feedback.rating = 'helpful')
        / nullif(count(feedback.id), 0) AS helpful_rate_pct
FROM public.product_events AS event
LEFT JOIN public.product_feedback AS feedback
    ON feedback.request_id = event.request_id
WHERE event.event_name = 'agda_question'
    AND event.metric_id IS NOT NULL
GROUP BY event.metric_id;

CREATE OR REPLACE VIEW public.analytics_status_summary AS
SELECT
    status,
    count(*) AS question_count,
    100.0 * count(*) / nullif(sum(count(*)) OVER (), 0) AS share_pct
FROM public.product_events
WHERE event_name = 'agda_question'
GROUP BY status;

-- Reason percentages use only negative feedback with a supplied reason.
-- Helpful feedback and negative feedback without a reason remain in the
-- overview/metric feedback totals, but do not invent a reason category.
CREATE OR REPLACE VIEW public.analytics_feedback_reasons AS
SELECT
    feedback.reason_code,
    count(*) AS feedback_count,
    100.0 * count(*) / nullif(sum(count(*)) OVER (), 0) AS share_pct
FROM public.product_feedback AS feedback
JOIN public.product_events AS event
    ON event.request_id = feedback.request_id
    AND event.event_name = 'agda_question'
WHERE feedback.rating = 'not_helpful'
    AND feedback.reason_code IS NOT NULL
GROUP BY feedback.reason_code;

COMMIT;
